        description: `### Product Overview\n${item.name} (${item.nameBn}) by ${item.brandName}. Premium grade ${item.oilType} refined for optimal nutrition, rich aroma, and wholesome authentic taste in everyday cooking.\n\n### Key Highlights\n- Authentic ${item.brandName} quality\n- High smoke point & pure refining standard\n- Enriched with essential fatty acids & vitamins\n- Net Quantity: ${item.packSize}`,
